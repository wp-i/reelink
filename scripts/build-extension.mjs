import { build } from 'esbuild'
import { spawnSync } from 'node:child_process'
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const { version } = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
const manifest = JSON.parse(readFileSync(join(root, 'extension/manifest.json'), 'utf8'))
if (manifest.version !== version) throw new Error('Extension and package versions must match')
const output = join(root, 'dist-extension')
// This directory is exclusively generated by this script.
if (dirname(output) !== root || !output.endsWith('dist-extension'))
  throw new Error('Invalid output directory')
const check = spawnSync(
  process.execPath,
  [join(root, 'node_modules/typescript/bin/tsc'), '-p', join(root, 'extension/tsconfig.json')],
  { stdio: 'inherit' },
)
if (check.status !== 0) process.exit(check.status || 1)
rmSync(output, { recursive: true, force: true })
mkdirSync(join(output, 'icons'), { recursive: true })
await build({
  absWorkingDir: root,
  entryPoints: ['background', 'offscreen', 'content', 'popup', 'capture'].map(
    (name) => `extension/${name}.ts`,
  ),
  outdir: output,
  bundle: true,
  format: 'iife',
  target: 'chrome116',
  legalComments: 'eof',
})
for (const file of ['manifest.json', 'popup.html', 'popup.css', 'offscreen.html', 'capture.html'])
  cpSync(join(root, 'extension', file), join(output, file))
for (const file of ['LICENSE', 'THIRD_PARTY_NOTICES.md'])
  cpSync(join(root, file), join(output, file))
cpSync(join(root, 'node_modules/jsqr/LICENSE'), join(output, 'jsQR-LICENSE.txt'))

// Reuse the optical PNG frames already shipped in the Windows icon.
const ico = readFileSync(join(root, 'src-tauri/icons/icon.ico'))
for (const size of [16, 32, 48, 128]) {
  const pngPath = join(
    root,
    'src-tauri/icons',
    size === 128 ? '128x128.png' : `${size}x${size}.png`,
  )
  // Smaller ICO frames are DIB; use Tauri's existing SVG rasterizer for exact brand artwork.
  if (size === 128) cpSync(pngPath, join(output, 'icons', `${size}.png`))
  else {
    const svg = readFileSync(join(root, 'public/reelink-logo.svg'), 'utf8')
    const master = svg.match(new RegExp(`<symbol id="mark-${size}"[^>]*>([\\s\\S]*?)</symbol>`))
    if (!master || ico.readUInt16LE(2) !== 1) throw new Error('Invalid icon source')
    const scratch = join(output, `icon-${size}.svg`)
    writeFileSync(
      scratch,
      `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}">${master[1]}</svg>`,
    )
    const result = spawnSync(
      process.execPath,
      [
        join(root, 'node_modules/@tauri-apps/cli/tauri.js'),
        'icon',
        scratch,
        '--output',
        join(output, 'icons'),
        '--png',
        String(size),
      ],
      { stdio: 'inherit' },
    )
    if (result.status !== 0) throw new Error('Extension icon generation failed')
    cpSync(join(output, 'icons', `${size}x${size}.png`), join(output, 'icons', `${size}.png`))
    rmSync(join(output, 'icons', `${size}x${size}.png`))
    rmSync(scratch)
  }
}
console.log(`Chrome extension: ${output}`)
if (process.argv.includes('--package')) {
  const archive = join(root, 'artifacts', `Reelink-Chrome-${version}.zip`)
  mkdirSync(dirname(archive), { recursive: true })
  // Native PowerShell handles local Windows paths; no cross-shell file operations.
  const quote = (value) => `'${value.replaceAll("'", "''")}'`
  const result = spawnSync(
    'powershell.exe',
    [
      '-NoProfile',
      '-Command',
      `Compress-Archive -LiteralPath ${quote(output)} -DestinationPath ${quote(archive)} -Force`,
    ],
    { stdio: 'inherit' },
  )
  if (result.status !== 0) throw new Error('Extension archive failed')
  console.log(`ZIP: ${archive}`)
}
